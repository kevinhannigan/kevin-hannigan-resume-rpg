import Phaser from 'phaser';
import { GB_COLORS, TILE_SIZE } from './constants';

const C = GB_COLORS;

type Px = number[][];

function drawPixels(
  gfx: Phaser.GameObjects.Graphics,
  pixels: Px,
  ox: number,
  oy: number,
  palette: Record<number, number>,
) {
  for (let y = 0; y < pixels.length; y++) {
    for (let x = 0; x < pixels[y].length; x++) {
      const c = palette[pixels[y][x]];
      if (c === undefined || c < 0) continue;
      gfx.fillStyle(c, 1);
      gfx.fillRect(ox + x, oy + y, 1, 1);
    }
  }
}

// 0=transparent, 1=darkest, 2=dark, 3=light, 4=lightest
const PAL: Record<number, number> = {
  0: -1,
  1: C.DARKEST,
  2: C.DARK,
  3: C.LIGHT,
  4: C.LIGHTEST,
};

function p(s: string): Px {
  return s.trim().split('\n').map((row) =>
    row.trim().split('').map(Number),
  );
}

export function generateAssets(scene: Phaser.Scene) {
  generateTiles(scene);
  generatePlayer(scene);
  generateNPCs(scene);
  generateBadger(scene);
  generateUI(scene);
}

function tex(scene: Phaser.Scene, key: string, w: number, h: number, draw: (g: Phaser.GameObjects.Graphics) => void) {
  const g = scene.add.graphics();
  draw(g);
  g.generateTexture(key, w, h);
  g.destroy();
}

function tileTex(scene: Phaser.Scene, key: string, pixels: Px) {
  tex(scene, key, TILE_SIZE, TILE_SIZE, (g) => drawPixels(g, pixels, 0, 0, PAL));
}

